// src/db/connection.rs

use log::{error, info};
use sqlx::postgres::PgPoolOptions;
use sqlx::PgPool;

/// Инициализация пула соединений PostgreSQL.
///
/// Это инфраструктурная точка старта приложения.
/// Если соединение с БД не удалось — приложение **не может**
/// продолжать работу в корректном состоянии.
///
/// Поэтому:
/// - при успехе логируем `info`
/// - при ошибке логируем `error` и завершаем процесс через `panic`
pub async fn init_pool(database_url: &str) -> PgPool {
    info!("Инициализация пула соединений к базе данных...");

    // Настройка пула:
    // - max_connections(10) — разумный дефолт для небольшого сервиса/бота
    //   (достаточно для параллельных апдейтов, но не перегружает БД)
    //
    // Здесь можно добавлять:
    // - connect_timeout
    // - idle_timeout
    // - max_lifetime
    // если понадобится более тонкий контроль.
    match PgPoolOptions::new()
        .max_connections(10)
        .connect(database_url)
        .await
    {
        Ok(pool) => {
            // Успешное подключение.
            // Этот лог важен при старте сервиса:
            // по нему легко увидеть, что приложение дошло до БД.
            info!("Успешное подключение к базе данных.");
            pool
        }

        Err(e) => {
            // Ошибка подключения к БД — критическая.
            //
            // Возможные причины:
            // - неверный DATABASE_URL
            // - БД недоступна (docker/container не запущен)
            // - проблемы с сетью / DNS
            // - превышен лимит подключений на стороне БД
            //
            // Логируем error, чтобы информация точно попала в логи
            // даже при уровне RUST_LOG=info.
            error!("Ошибка подключения к базе данных: {:?}", e);

            // panic здесь оправдан:
            // сервис без БД работать не может,
            // а попытки "продолжить" приведут к каскадным ошибкам.
            panic!("Failed to connect to the database");
        }
    }
}
