// src/db/mod.rs
//! DB слой приложения (PostgreSQL / sqlx).
//!
//! Назначение модуля `db` — изолировать доступ к данным от остального приложения.
//! В идеале внешний код (bot/domain) не должен знать о деталях хранения, SQL, таблицах.
//!
//! Структура:
//! - `connection`      — инициализация пула соединений (PgPool) и базовые настройки.
//! - `students_repo`   — репозиторий для работы со студентами (CRUD/поиск).
//! - `user_states_repo`— репозиторий для состояния регистрации/сессии пользователя.
//! - `facade`          — фасад, объединяющий несколько repo в удобный API для верхних слоёв.
//!
//! Почему так:
//! - Repo-слой упрощает тестирование и локализацию SQL.
//! - Facade снижает связность: боту не нужно понимать, что данные лежат в 2+ таблицах.
//!
//! Логи:
//! - В этом файле логи не нужны, потому что это только объявления модулей.
//! - Логировать стоит в `connection` (создание пула) и в `facade`/repo при ошибках запросов.

pub mod connection;
pub mod facade;
pub mod students_repo;
pub mod user_states_repo;
