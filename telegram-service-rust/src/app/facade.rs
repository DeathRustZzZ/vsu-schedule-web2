// src/app/facade.rs

// Импортируем конфигурацию приложения (AppConfig содержит настройки вроде токена бота, URL базы и т.д.)
use crate::config::AppConfig;

// Импортируем фасад для работы с базой данных.
// DbFacade инкапсулирует доступ к репозиториям и скрывает детали SQL-запросов.
use crate::db::facade::DbFacade;

// Импортируем функцию запуска Telegram-бота.
// Она отвечает за настройку и запуск основного цикла обработки сообщений.
use crate::services::telegram::run_telegram_bot;

// PgPool — пул соединений SQLx к PostgreSQL.
// Позволяет эффективно работать с базой без постоянного открытия новых соединений.
use sqlx::PgPool;

/// Точка входа в приложение.
/// Здесь мы связываем все основные компоненты: конфигурацию, базу данных и Telegram-бота.
///
/// - `config`: объект конфигурации приложения (например, токен бота, параметры базы).
/// - `pool`: пул соединений к PostgreSQL.
///
/// Функция асинхронная, потому что запуск бота и работа с базой требуют async.
pub async fn run_app(config: AppConfig, pool: PgPool) {
    // Создаём фасад базы данных, передавая ему пул соединений.
    // Теперь все операции с БД будут идти через этот фасад.
    log::info!("Создаём DbFacade...");
    let db_facade = DbFacade::new(pool);

    // Инициализируем Telegram-бота, используя токен из конфигурации.
    // clone() нужен, потому что токен — это строка, и мы передаём её в новый объект.
    log::info!("Инициализируем Telegram-бота...");
    let bot = teloxide::Bot::new(config.bot_token.clone());

    run_telegram_bot(bot, db_facade).await;
    log::info!("Telegram-бот завершил работу.");
}

